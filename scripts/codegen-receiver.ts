/**
 * Regenerates packages/shared/src/receiver-bytecode.ts from the Foundry artifact of PaymentReceiver.
 * Run after ANY change to contracts/PaymentReceiver.sol (and `forge build`): `bun run contracts:codegen`.
 * The receiver address is derived offline from this creation code, so a stale file would point customers
 * at the wrong address. The API also verifies the derivation against the chain at startup.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { keccak256, type Hex } from 'viem';

interface Artifact { bytecode: { object: Hex } }
const artifact = JSON.parse(readFileSync('contracts/out/PaymentReceiver.sol/PaymentReceiver.json', 'utf8')) as Artifact;
const code = artifact.bytecode.object;
if (!/^0x[0-9a-f]+$/.test(code) || code.length < 100) throw new Error('Unexpected PaymentReceiver bytecode');

const out = `// GENERATED by scripts/codegen-receiver.ts from contracts/PaymentReceiver.sol. Do not edit.
// Regenerate with \`bun run contracts:build && bun run contracts:codegen\` after any receiver change.
import type { Hex } from 'viem';

/** Creation code of PaymentReceiver without constructor arguments. */
export const PAYMENT_RECEIVER_CREATION_CODE: Hex =
  '${code}';

/** keccak256 of the creation code, for drift detection against the artifact. */
export const PAYMENT_RECEIVER_CREATION_CODE_HASH: Hex = '${keccak256(code)}';
`;
writeFileSync('packages/shared/src/receiver-bytecode.ts', out);
console.log(`wrote receiver-bytecode.ts (${(code.length - 2) / 2} bytes)`);
